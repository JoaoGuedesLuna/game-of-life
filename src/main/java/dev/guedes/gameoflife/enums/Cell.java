package dev.guedes.gameoflife.enums;

/**
 * Represents the state of a cell in the Game of Life.
 * <p>
 * A cell can be either:
 * <ul>
 *     <li>{@link #ALIVE} – the cell is currently alive</li>
 *     <li>{@link #DEAD} – the cell is currently dead</li>
 * </ul>
 * </p>
 *
 * @author João Guedes
 */
public enum Cell {
    ALIVE,
    DEAD
}
